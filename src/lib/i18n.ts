export type MessageKey = keyof typeof ptBr;

export const dictionaries: Record<Language, Dictionary> = { 'pt-BR': ptBr, en };

export function translate(lang: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}

export function formatDate(lang: Language, date: Date): string {
  return new Intl.DateTimeFormat(lang, { day: '2-digit', month: 'short', year: 'numeric', timeZone: 'UTC' }).format(date);
}

